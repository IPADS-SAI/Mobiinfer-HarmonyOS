#!/bin/bash
set -euo pipefail
MOBI_SOURCE_ROOT="${MOBI_ROOT:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)}"
: "${HARMONY_HOME:?Set HARMONY_HOME to the SDK openharmony directory}"
cmake -S "$MOBI_SOURCE_ROOT" -B "$PWD" \
-DCMAKE_TOOLCHAIN_FILE="$HARMONY_HOME/native/build/cmake/ohos.toolchain.cmake" \
-DCMAKE_BUILD_TYPE=Release \
-DOHOS_ARCH="arm64-v8a" \
-DOHOS_STL=c++_static \
-DMNN_USE_LOGCAT=true \
-DMNN_BUILD_BENCHMARK=ON \
-DMNN_USE_SSE=OFF \
-DMNN_SUPPORT_BF16=OFF \
-DMNN_BUILD_TEST=ON \
-DOHOS_PLATFORM_LEVEL=20  \
-DMNN_BUILD_LLM=ON \
-DMNN_BUILD_LLM_OMNI=ON \
-DMNN_SEP_BUILD=OFF \
-DHIAI_VERBOSE=ON \
-DHIAI_INT8_DIAG=0 \
-DMNN_HIAI_CACHE_OM_BY_CHUNK=ON \
-DMNN_HIAI_FREE_CONST_HOST=1 \
-DMNN_LOW_MEMORY=ON \
-DMNN_SUPPORT_TRANSFORMER_FUSE=ON \
-DMNN_BUILD_SHARED_LIBS=ON \
-DMOBIINFER_MNN=OFF \
-DMNN_NPU:BOOL=true \
-DNATIVE_LIBRARY_OUTPUT=. -DNATIVE_INCLUDE_OUTPUT=. "$@"

cmake --build "$PWD" --parallel "${MOBI_BUILD_JOBS:-8}"
